@afm_app.command("read")
def afm_read(
    scan: Path = typer.Argument(..., help=SCAN_ARGUMENT_HELP),
    channel: str | None = CHANNEL_OPTION,
    as_json: bool = JSON_OPTION,
) -> None:
    """Read a scan and report what it is. Measures nothing.

    Worth running first on a partner's file: if the pixel pitch or the height
    units are wrong, every dimension downstream is wrong by the same factor and
    nothing else in the pipeline can tell. Native files are read directly,
    through AFMReader; there is no export step.
    """
    from dobladillo.imaging.readers import SINGLE_PITCH, UnreadableScan, read, suffix_of

    emitter = Emitter(as_json)
    try:
        image = read(scan, channel=channel)
    except UnreadableScan as e:
        emitter.fail(str(e), kind="unreadable_scan")
        return
    rows, cols = image.shape
    height_nm, width_nm = image.size_nm
    payload: dict[str, Any] = {
        "source": image.source,
        "pixels": {"rows": rows, "cols": cols},
        "pixel_nm": round(image.pixel_nm, 4),
        "scan_nm": {"height": round(height_nm, 1), "width": round(width_nm, 1)},
        "heights_nm": {
            "min": round(float(image.heights_nm.min()), 3),
            "max": round(float(image.heights_nm.max()), 3),
            "median": round(float(_median(image.heights_nm)), 3),
        },
        # AFMReader reports one pitch for these formats, from one axis, and
        # nothing here can check the other. Said, so it is not assumed.
        "square_pixels_checked": suffix_of(scan) not in SINGLE_PITCH,
    }
    heights = payload["heights_nm"]
    rows_out = [
        ("source", str(payload["source"])),
        ("pixels", f"{rows} x {cols}"),
        ("pixel size", f"{payload['pixel_nm']} nm"),
        ("scan size", f"{height_nm:.0f} x {width_nm:.0f} nm"),
        (
            "heights",
            f"{heights['min']} to {heights['max']} nm, median {heights['median']}",
        ),
    ]
    if not payload["square_pixels_checked"]:
        rows_out.append(("square pixels", "assumed, not checked: the format gives one pitch"))
    emitter.result(payload, "scan\n" + _table(rows_out))


@afm_app.command("measure")
def afm_measure(
    scan: Path = typer.Argument(..., help=SCAN_ARGUMENT_HELP),
    channel: str | None = CHANNEL_OPTION,
    length: float = typer.Option(191.0, help=EXPECTED_OPTION_HELP.format("length")),
    width: float = typer.Option(36.0, help=EXPECTED_OPTION_HELP.format("width")),
    height: float = typer.Option(2.0, help=EXPECTED_OPTION_HELP.format("height")),
    tolerance: float = typer.Option(0.2, help="Fractional tolerance on length and width."),
    tip_radius: float = typer.Option(
        ...,
        help="Tip apex radius, nm, MEASURED not nominal. Required: without it the "
        "particles are compared against the object while the image shows the object "
        "plus the tip, and a perfectly good scan reads as 0% well formed.",
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Flatten, segment, measure and classify a scan, and report the yield.

    **The expected dimensions are of the object, and the image is not.** A
    half-height footprint is wider by twice sqrt(R*h - h^2/4) -- 8.7 nm for a
    10 nm tip on a 2 nm plate, a quarter of a 36 nm width -- so classifying the
    image against the object's own size marks every particle malformed.

    This used to take the object's dimensions and compare them to the image
    directly. On a correct synthetic scan it reported 0 of 40 well formed,
    which is the most misleading answer available: it looks like a fold that
    failed rather than a comparison that was never valid.

    So the tip radius is required, the measurements are deconvolved before
    classification, and both the raw and corrected figures are reported.

    The yield carries a Wilson interval rather than a bare fraction, because
    eleven of twelve and ninety of a hundred are not the same claim.
    """
    import statistics

    from dobladillo.compare.corrections import half_height_broadening_nm
    from dobladillo.imaging.classify import population, well_formed_particles
    from dobladillo.imaging.flatten import flatten
    from dobladillo.imaging.particles import find_particles
    from dobladillo.imaging.readers import UnreadableScan, read

    emitter = Emitter(as_json)
    try:
        image = read(scan, channel=channel)
    except UnreadableScan as e:
        emitter.fail(str(e), kind="unreadable_scan")
        return

    flattened, background = flatten(image)
    particles = find_particles(flattened, background)
    if not particles:
        emitter.fail("no particles found in that scan", kind="no_particles")
        return

    # Height is not broadened -- a tip does not make a plate taller -- so the
    # measured height is what sets the correction for the lateral dimensions.
    inside = [p for p in particles if not p.touches_edge] or particles
    observed_height = statistics.median([p.height_nm for p in inside])
    widening = 2 * half_height_broadening_nm(
        tip_radius_nm=tip_radius, feature_height_nm=observed_height
    )

    # Classify against the object's dimensions PLUS the tip, which is what the
    # image contains. Equivalent to deconvolving every particle and comparing
    # against the object, and it leaves the reported sizes as measured.
    found = population(
        particles,
        length_nm=length + widening,
        width_nm=width + widening,
        height_nm=height,
        tolerance=tolerance,
    )
    # Averaged over the WELL-FORMED particles, not over everything inside the
    # frame: an aggregate is not a measurement of the rectangle, and four of
    # them among thirty-eight rectangles move the mean length by 6%. See
    # `classify.well_formed_particles`. If nothing is well formed there is no
    # such average to take, and the fall-back says so in the payload.
    measured = well_formed_particles(
        particles,
        length_nm=length + widening,
        width_nm=width + widening,
        height_nm=height,
        tolerance=tolerance,
    )
    measured_over = "well-formed particles"
    if not measured:
        measured, measured_over = (
            inside,
            "every particle clear of the frame edge (none was well formed)",
        )
    raw_length = statistics.fmean([p.length_nm for p in measured])
    raw_width = statistics.fmean([p.width_nm for p in measured])
    payload = {
        "source": image.source,
        "expected_nm": {"length": length, "width": width, "height": height},
        "tip_radius_nm": tip_radius,
        "widening_nm": round(widening, 2),
        "measured_nm": {"length": round(raw_length, 1), "width": round(raw_width, 1)},
        "deconvolved_nm": {
            "length": round(raw_length - widening, 1),
            "width": round(raw_width - widening, 1),
        },
        "particles_found": len(particles),
        "measured_over": measured_over,
        "measured_particles": len(measured),
        **found.as_dict(),
    }
    fraction = found.well_formed.as_dict()
    rows_out = [
        ("source", image.source),
        ("particles found", str(len(particles))),
        ("excluded at edge", str(found.excluded_at_edge)),
        ("counted", str(found.total)),
        (
            "tip widening",
            f"{widening:.1f} nm, for a {tip_radius:.0f} nm tip on a "
            f"{observed_height:.1f} nm feature",
        ),
        (
            "measured",
            f"{raw_length:.1f} x {raw_width:.1f} nm, over {len(measured)} {measured_over}",
        ),
        (
            "deconvolved",
            f"{raw_length - widening:.1f} x {raw_width - widening:.1f} nm "
            f"(expected {length:g} x {width:g})",
        ),
    ]
    rows_out += [(f"  {k}", str(v)) for k, v in sorted(found.counts.items())]
    rows_out.append(("well formed", str(fraction)))
    emitter.result(payload, "measurement\n" + _table(rows_out))


@afm_app.command("synthetic")
def afm_synthetic(
    out: Path = typer.Option(..., "--out", help="Where to write the .gsf."),
    part: str = typer.Option(
        "twist-corrected", help="Whose dimensions to place. Must be a part this builds."
    ),
    seed: int = typer.Option(0, help="Which scan to generate."),
    rectangles: int = typer.Option(40, help="How many well-formed particles to place."),
    realistic: bool = typer.Option(
        False,
        "--realistic",
        help="Add the artefacts a real scan carries: scanner bow, thermal drift shear "
        "and a tip-change streak. Use this to test an analysis, not to demonstrate one.",
    ),
    lp: float = typer.Option(
        1500.0, "--lp", help="bundle only: persistence length the rods are drawn from, nm."
    ),
    arc_radius: float | None = typer.Option(
        None, "--arc-radius", help="bundle only: give every rod a built-in arc of this radius, nm."
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Write a synthetic scan of known contents, as a .gsf.

    For the bundle it places rods of the design's length, their shapes drawn
    from a wormlike chain of persistence length `--lp` -- and, with
    `--arc-radius`, curved as the old misphased routings were -- at 1024 px
    over 2 um, the resolution the E10 protocol asks for.

    Two uses. It is how this project's own measurement is validated, against
    ground truth we chose rather than against another measurement. And it is
    the cheapest way to check a partner's end of the pipeline before any real
    sample is imaged: send them this, ask what they measure, and a disagreement
    is located before it is attributed to the chemistry.
    """
    from dobladillo.imaging.readers import write_gsf
    from dobladillo.imaging.synthetic import synthetic_scan

    emitter = Emitter(as_json)
    # The dimensions come from the part rather than from a constant in the
    # imaging module. `imaging` knows nothing about DNA on purpose -- that is
    # what lets it be handed to a lab with no interest in the rest of this --
    # so the CLI, which does know about parts, is where the two meet. Its
    # defaults used to be 191 x 36 nm, which is the twist-pair arm, matching
    # one part by coincidence and the rectangle not at all.
    built = _make_part(part, emitter)
    if part == "bundle":
        from dobladillo.imaging.synthetic import synthetic_rod_scan

        size = built.as_dict()["approx_dimensions_nm"]
        rods = synthetic_rod_scan(
            seed=seed,
            n_rods=rectangles,
            contour_nm=size["length"],
            height_nm=size["diameter"],
            lp_nm=lp,
            curvature_per_nm=1.0 / arc_radius if arc_radius else 0.0,
            n_fragments=2,
            n_aggregates=2,
            bow_nm=4.0 if realistic else 0.0,
            drift_shear=0.05 if realistic else 0.0,
            streak_lines=12 if realistic else 0,
        )
        write_gsf(rods.image, out, title=f"synthetic rods seed {seed}")
        kinds = [p.kind for p in rods.truth]
        rod_truth = {
            "part": part,
            "contour_nm": size["length"],
            "height_nm": size["diameter"],
            "persistence_length_nm": lp,
            "arc_radius_nm": arc_radius,
            "tip_radius_nm": 10.0,
            **{k: kinds.count(k) for k in ("rod", "fragment", "aggregate")},
            "artefacts": "bow+drift+streak" if realistic else "none",
        }
        emitter.result(
            {"file": str(out), "seed": seed, "part": part, "ground_truth": rod_truth},
            "synthetic scan\n"
            + _table([("wrote", str(out))] + [(k, str(v)) for k, v in rod_truth.items()]),
        )
        return
    dimensions = sorted(
        (float(v) for v in built.as_dict()["approx_dimensions_nm"].values()), reverse=True
    )
    # Typical of a working instrument rather than a broken one: enough bow to
    # defeat a plane fit, drift over a multi-minute scan, and one tip event.
    scan = synthetic_scan(
        seed=seed,
        n_rectangles=rectangles,
        length_nm=dimensions[0],
        width_nm=dimensions[-1],
        bow_nm=4.0 if realistic else 0.0,
        drift_shear=0.05 if realistic else 0.0,
        streak_lines=12 if realistic else 0,
    )
    write_gsf(scan.image, out, title=f"synthetic seed {seed}")
    truth = {
        "part": part,
        "length_nm": round(dimensions[0], 1),
        "width_nm": round(dimensions[-1], 1),
        "placed": len(scan.truth),
        "rectangles": len(scan.rectangles),
        "aggregates": len(scan.truth) - len(scan.rectangles),
    }
    truth["artefacts"] = "bow+drift+streak" if realistic else "none"
    payload = {"file": str(out), "seed": seed, "part": part, "ground_truth": truth}
    emitter.result(
        payload,
        "synthetic scan\n"
        + _table(
            [("wrote", str(out)), ("seed", str(seed))] + [(k, str(v)) for k, v in truth.items()]
        ),
    )


