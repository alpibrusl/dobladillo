@app.command()
def lint(
    design_file: Path = typer.Argument(..., help="A .sc design file."),
    only: list[str] | None = ONLY_OPTION,
    limit: int = LIMIT_OPTION,
    as_json: bool = JSON_OPTION,
) -> None:
    """Check a design against the rules. Exits non-zero on a hard violation.

    Warnings never change the exit code: they are preferences that published
    designs break routinely, and a lint that fails on them would just be
    switched off.
    """
    from dobladillo.routing.rules import lint as run_lint

    out = Emitter(as_json)
    if not design_file.is_file():
        out.fail(f"no such file: {design_file}", kind="missing_file", code=2)
        return
    try:
        design = ad.read_design(design_file)
    except Exception as e:  # scadnano raises several unrelated types
        out.fail(f"could not read {design_file}: {e}", kind="unreadable_design", code=2)
        return

    try:
        report = run_lint(design, only=only or None)
    except ValueError as e:
        out.fail(str(e), kind="unknown_rule")
        return

    payload = report.as_dict(limit=None if limit == 0 else limit)
    payload["design"] = str(design_file)

    counts = payload["counts"]
    head = (
        f"{design_file}: {counts['violations']} violations, {counts['warnings']} warnings"
        if report.violations
        else f"{design_file}: clean"
    )
    lines = [head]
    if payload["by_rule"]:
        lines.append(_table([(k, str(v)) for k, v in payload["by_rule"].items()]))
    for finding in payload["findings"]:
        where = f"helix {finding['helix']} offset {finding['offset']}"
        lines.append(
            f"  {finding['severity']:9s} {finding['rule']:20s} {finding['message']} [{where}]"
        )
    if payload["truncated"]:
        lines.append("  ... more not shown; raise --limit (0 for all)")
    lines.append("  not checked: " + ", ".join(e["rule"] for e in payload["not_checked"]))
    out.result(payload, "\n".join(lines))

    if not report.ok:
        raise typer.Exit(1)


@app.command()
def predict(
    target: str = typer.Argument(
        ...,
        help="A part (rectangle, bundle, hinge, twist-corrected, twist-uncorrected) "
        "or a .sc design file.",
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Predict a design's equilibrium bend and twist in seconds (beam model).

    A CanDo-class model: helices as beams on their lattice, crossovers rigid,
    stress from lattice twist and from deletions and insertions. It CANNOT see
    crossovers made on the wrong face of a helix -- run `lint` for that; a
    design that fails `crossover_azimuth` gets a prediction that is wrong.
    """
    from dobladillo.mechanics.beam import predict as run_predict

    out = Emitter(as_json)
    path = Path(target)
    if path.suffix == ".sc":
        if not path.is_file():
            out.fail(f"no such file: {path}", kind="missing_file", code=2)
            return
        try:
            design = ad.read_design(path)
        except Exception as e:  # scadnano raises several unrelated types
            out.fail(f"could not read {path}: {e}", kind="unreadable_design", code=2)
            return
    else:
        design = _make_part(target, out).design

    from dobladillo.routing.azimuth import measure

    try:
        result = run_predict(design)
    except ValueError as e:
        out.fail(str(e), kind="unsupported_design")
        return
    # Deletions and insertions strain crossovers on purpose -- that is how a
    # curved design bends, and the model handles it. Only placement counts.
    phasing = measure(design, count_skips=False)
    payload = {"design": target, **result.as_dict()}
    payload["cannot_see"] = "misphased crossovers; see `lint --rule crossover_azimuth`"
    payload["valid"] = phasing.acceptable
    payload["phasing_rms_deg"] = round(phasing.rms_deg, 1)
    radius = (
        "straight"
        if result.straight
        else f"{result.radius_nm:.0f} nm toward {result.bend_direction_deg:.0f} deg"
    )
    rows = []
    if not phasing.acceptable:
        rows.append(
            (
                "NOT VALID",
                f"crossovers misphased ({phasing.rms_deg:.0f} deg rms); this model cannot "
                "see that, so the shape below is not a prediction",
            )
        )
    rows += [
        ("bend radius", radius),
        ("sagitta", f"{result.sagitta_nm:.1f} nm over {result.length_nm:.0f} nm"),
        ("twist", f"{result.twist_deg:+.0f} deg end to end (+ = right-handed)"),
        ("model", f"{result.nodes} nodes, {result.crossovers} crossovers, {result.seconds:.1f} s"),
        ("cannot see", payload["cannot_see"]),
    ]
    out.result(payload, f"{target}: predicted shape\n" + _table(rows))


def _design_hash(design: Any) -> str:
    """The design's content hash; see `dobladillo.provenance`."""
    from dobladillo.provenance import design_sha256

    return design_sha256(design)


@app.command()
def benchmark(
    case: list[str] | None = typer.Option(
        None, "--case", help="Run only cases whose id starts with this. Repeatable."
    ),
    manifest: Path | None = typer.Option(
        None, "--manifest", help="A known-answers file; default tests/data/known_answers.json."
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Score routing and shape prediction against known answers. Exits non-zero on a miss.

    Published designs must pass phasing; the old bundles, which oxDNA showed
    bent, must fail it; the beam model must reproduce composite-beam theory
    and is scored against Dietz 2009's measured bend. Known failures are
    reported and do not fail the run; one that starts passing does.
    """
    from dobladillo.benchmark import DEFAULT_MANIFEST
    from dobladillo.benchmark import run as run_benchmark

    out = Emitter(as_json)
    path = manifest or DEFAULT_MANIFEST
    if not path.is_file():
        out.fail(f"no known-answers file at {path}", kind="missing_file", code=2)
        return
    try:
        report = run_benchmark(path, only=case or None)
    except ValueError as e:
        out.fail(str(e), kind="bad_manifest", code=2)
        return
    payload = report.as_dict()
    lines = [
        f"{c.status.upper():16s} {c.id:40s} {c.expect:4s} "
        + ", ".join(f"{k}={v}" for k, v in c.observed.items() if not isinstance(v, dict))
        for c in report.cases
    ]
    lines.append("")
    lines.append(", ".join(f"{n} {s}" for s, n in report.counts().items()))
    lines += [f"  known failure {c.id}: {c.known_failure}" for c in report.cases if c.known_failure]
    lines += [f"  wanted {w['id']}: {w['why_not']}" for w in report.wanted]
    out.result(payload, "\n".join(lines))
    if not report.ok:
        raise typer.Exit(1)


def _folding_window_or_none(design: Any) -> dict[str, Any] | None:
    """The folding window for a design with sequences, or None if it has none."""
