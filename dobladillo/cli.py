@app.command("folding-window")
def folding_window_command(
    part: str = typer.Argument(..., help="A part name, as for `lab order`."),
    mg_mm: float = typer.Option(12.0, "--mg-mm", help="MgCl2 in the folding buffer, mM."),
    staple_nm: float = typer.Option(50.0, "--staple-nm", help="Each staple, nM (E1: 50)."),
    scaffold_nm: float = typer.Option(10.0, "--scaffold-nm", help="Scaffold, nM."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Where this design should fold: staple melting temperatures, weak staples, a screen.

    Isolated staple-against-scaffold melting temperatures in the folding
    buffer. Folding is cooperative and happens above them, so this points an
    isothermal screen (E11) and names the staples that bind last; it does not
    predict the best folding temperature.
    """
    from dobladillo.sequence.folding import folding_window

    out = Emitter(as_json)
    built = _make_part(part, out)
    try:
        window = folding_window(
            built.design, magnesium_mm=mg_mm, staple_nm=staple_nm, scaffold_nm=scaffold_nm
        )
    except ValueError as e:
        out.fail(str(e), kind="no_sequences")
        return
    payload = {"part": part, **window.as_dict()}
    tm = payload["staple_tm_c"]
    rows = [
        ("staple Tm", f"median {tm['median']} C, 10-90% {tm['p10']}-{tm['p90']} C"),
        (
            "screen",
            f"isothermal {payload['isothermal_screen_c'][0]}-"
            f"{payload['isothermal_screen_c'][1]} C (gradient block)",
        ),
        ("weak staples", str(len(payload["weak_staples"]))),
    ]
    rows += [
        (f"  helix {w['helix']} @ {w['offset']}", f"{w['tm_c']} C, {w['length_nt']} nt")
        for w in payload["weak_staples"][:10]
    ]
    rows.append(("caveat", "isolated melting; the fold is cooperative and sits above these"))
    out.result(payload, f"{part}: folding window at {mg_mm} mM Mg\n" + _table(rows))


#: Every part `_make_part` builds, and so every part `lab` and `experiment new`
#: accept; `experiment new` also takes E9's `dimer`.
PARTS: tuple[str, ...] = (
    "rectangle",
    "bundle",
    "hinge",
    "hinge-locked-open",
    "hinge-locked-latched",
    "twist-corrected",
    "twist-uncorrected",
    "pattern",
    "calibration-tile",
    "calibration-tile-biotin",
)
EXPERIMENT_PARTS: tuple[str, ...] = (*PARTS, "dimer")


def _make_part(which: str, out: Emitter) -> Any:
    if which == "rectangle":
        from dobladillo.parts.rectangle import rothemund_rectangle

        return rothemund_rectangle()
    if which == "bundle":
        from dobladillo.parts.bundle import six_helix_bundle

        return six_helix_bundle()
    if which == "hinge":
        from dobladillo.parts.hinge import bistable_hinge

        return bistable_hinge()
    if which == "pattern":
        from dobladillo.parts.pattern import patterned_rectangle

        return patterned_rectangle()
    if which in ("calibration-tile", "calibration-tile-biotin"):
        from dobladillo.parts.calibration_tile import calibration_tile

        return calibration_tile(marker="biotin" if which.endswith("biotin") else "hairpin")
    if which in ("hinge-locked-open", "hinge-locked-latched"):
        # E4's two FRET references: the same hinge, locked in one state.
        from dobladillo.hamiltonian.bracket import locked_references
        from dobladillo.parts.hinge import bistable_hinge

        if which == "hinge-locked-open":
            return bistable_hinge(latch_sequence=None)
        refs = locked_references()
        seqs, helices = refs.latched_sequences, refs.latched_helices
        return bistable_hinge(
            latch_sequence=seqs[0],
            latch_helix=helices[0],
            extra_latches=tuple(zip(seqs[1:], helices[1:], strict=True)),
        )
    if which in ("twist-corrected", "twist-uncorrected"):
        from dobladillo.parts.twist_pair import twist_pair

        pair = twist_pair()
        return pair.corrected if which == "twist-corrected" else pair.uncorrected
    out.fail(
        f"unknown part {which!r}; use rectangle, bundle, hinge, hinge-locked-open, "
        "hinge-locked-latched, twist-corrected, twist-uncorrected or pattern",
        kind="unknown_part",
    )
    return None


def _order_of(built: Any, *, plate: int, out: Emitter) -> tuple[Any, Any, dict[str, Any] | None]:
    """What to order for a part: its design, or -- for a variant that reuses
    another part's plates -- only its own staples, and which of the other
    part's wells to leave out of the pool. Returns (design, layout, reuse)."""
    from dobladillo.lab import plates as lab

    if not hasattr(built, "order_design"):
        return built.design, lab.name_and_assign_wells(built.design, plate_type=plate), None
    design = built.order_design()
    layout = lab.name_and_assign_wells(
        design, plate_type=plate, plate_prefix="marker", name_suffix="_hp"
    )
    base = _make_part(built.base_part, out)
    reuse = lab.shared_pool(
        base.design, built.design, base_part=built.base_part, plate_type=plate
    ).as_dict()
    return design, layout, reuse


@lab_app.command("order")
def lab_order(
    part: str = PART_ARGUMENT,
    out_dir: Path | None = OUT_OPTION,
    plate: int = PLATE_OPTION,
    as_json: bool = JSON_OPTION,
) -> None:
    """Plates, pooling map and cost for ordering a part's staples.

    Validates what it writes rather than trusting that no exception means a
    file IDT would accept. `dimer` (E9) orders only the extended staples of A
    and B and says which of E1's wells to pool and which to skip.
    """
    from dobladillo.lab import plates as lab

    emitter = Emitter(as_json)
    if plate not in (96, 384):
        emitter.fail(f"plate must be 96 or 384, got {plate}", kind="invalid_parameters")
        return
    if part == "dimer":
        _order_dimer(emitter, out_dir)
        return
    built = _make_part(part, emitter)
    order, layout, reuse = _order_of(built, plate=plate, out=emitter)

    problems = lab.validate_bulk_csv(lab.bulk_csv_rows(order))
    payload: dict[str, Any] = {
        "part": part,
        **layout.as_dict(),
        "pooling": layout.pooling_map(),
        "pipetting": lab.pipetting_sheet(layout),
        "problems": [p.as_dict() for p in problems],
    }
    if reuse is not None:
        payload["reuse"] = reuse

    if out_dir is not None:
        from dobladillo import provenance

        written = lab.write_order_files(order, directory=out_dir, name=part, plate_type=plate)
        if reuse is not None:
            written["reuse"] = out_dir / f"{part}_reuse.json"
            written["reuse"].write_text(json.dumps(reuse, indent=2) + "\n")
        problems += lab.validate_plate_workbook(written["idt_plate_xlsx"], plate_type=plate)
        payload["problems"] = [p.as_dict() for p in problems]
        # Ties these oligos to the design they came from, wherever they are
        # written -- including over an experiment's pre/order, where a design
        # that no longer matches the prediction then shows up as a mismatch.
        manifest = provenance.write_order_manifest(
            out_dir,
            name=part,
            part=part,
            design_hash=provenance.design_sha256(built.design),
            files=list(written.values()),
        )
        payload["files"] = {k: str(v) for k, v in written.items()}
        payload["manifest"] = str(manifest)

    payload["valid"] = not problems

    cost = layout.cost
    rows = [
        ("plates", f"{len(layout.plates)} x {plate}-well: {', '.join(layout.plates)}"),
        ("staples", str(len(layout.wells))),
        ("total bases", f"{cost.total_nt:,}"),
        ("estimated cost", f"{cost.total:,.2f} at {cost.price_per_base}/base"),
        ("order files valid", "yes" if not problems else f"NO, {len(problems)} problems"),
    ]
    if reuse is not None:
        rows.append(
            (
                "reuses",
                f"{reuse['reused_from_base']} staples from the {reuse['base_part']} plates; "
                f"pool them all EXCEPT {len(reuse['omit_from_base'])} wells, plus these "
                f"{reuse['new_staples']}",
            )
        )
    rows.extend((f"wrote {k}", v) for k, v in payload.get("files", {}).items())
    if "manifest" in payload:
        rows.append(("wrote manifest", payload["manifest"]))
    body = f"{part}: staple order\n" + _table(rows)
    body += "\n\n  Cost assumptions:\n" + _table([("-", a) for a in cost.assumptions])
    for problem in problems[:10]:
        body += f"\n  PROBLEM {problem.where}: {problem.message}"
    emitter.result(payload, body)

    if problems:
        raise typer.Exit(1)


