@experiment_app.command("assembly")
def experiment_assembly(
    directory: Path = typer.Argument(..., help="An assembly (E9) experiment folder."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Count assembly states per sample, against the controls. Writes post/assembly.json.

    Samples are named by their files, `during/raw/<sample>-<NN>.<ext>`: A and B
    alone are the controls, R1, R2, ... the replicate mixes, anything else a
    series point. Each sample gets monomer, dimer, larger and malformed
    fractions with 95% Wilson intervals; each mixture its dimer fraction above
    the controls' with a Newcombe interval; the replicates a chi-square test of
    one shared distribution.

    It refuses rather than substitutes: a missing tip radius, reference height
    or control stops it. Exits 1 when a sample has fewer than 100 counted
    particles.
    """
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.arms import RecordIncomplete
    from dobladillo.experiments.assembly import MIN_PER_SAMPLE, analyse
    from dobladillo.imaging.readers import UnreadableScan

    emitter = Emitter(as_json)
    state = run_check(directory)
    try:
        result = analyse(directory)
    except RecordIncomplete as e:
        emitter.fail(str(e), kind=e.kind)
        return
    except UnreadableScan as e:
        emitter.fail(str(e), kind="unreadable_scan")
        return
    result["record"] = state.as_dict()
    post = directory / "post"
    post.mkdir(exist_ok=True)
    (post / "assembly.json").write_text(json.dumps(result, indent=2) + "\n")

    background = result["controls"]["dimer_fraction"]
    lines = [
        f"controls A+B: dimer {background['fraction']:.0%} "
        f"({background['count']}/{background['total']}), "
        f"95% [{background['ci95'][0]:.0%}, {background['ci95'][1]:.0%}]"
    ]
    for name, sample in result["samples"].items():
        counts = sample["counts"]
        line = f"{name:>6} ({sample['role']}): {sample['counted']} counted  " + "  ".join(
            f"{k} {v}" for k, v in counts.items()
        )
        if "dimer_minus_controls" in sample:
            d = sample["dimer_minus_controls"]
            line += (
                f"   dimer above controls {d['difference']:+.0%} "
                f"[{d['ci95'][0]:+.0%}, {d['ci95'][1]:+.0%}]"
            )
        lines.append(line)
    repro = result["reproducibility"]
    if "p_value" in repro:
        lines.append(
            f"replicates {', '.join(repro['samples'])}: chi2 {repro['chi2']:.2f}, "
            f"p = {repro['p_value']:.3f}"
        )
    else:
        lines.append(repro["note"])
    lines.append(f"wrote {post / 'assembly.json'}")
    lines += [f"RECORD: {p}" for p in state.problems]
    emitter.result({"directory": str(directory), **result}, f"{directory}\n" + "\n".join(lines))
    if result["too_few_particles"]:
        emitter.note(
            f"fewer than {MIN_PER_SAMPLE} counted particles in "
            f"{', '.join(result['too_few_particles'])}. Image more before interpreting."
        )
        raise typer.Exit(1)


@experiment_app.command("pattern")
def experiment_pattern(
    directory: Path = typer.Argument(..., help="A patterned-rectangle (E8) experiment folder."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Read the designed pattern off every well-formed particle, and say which way round.

    Writes `post/pattern.json`. Scans are `during/raw/pattern-*` (the
    patterned sample) and `during/raw/control-*` (E1's plain rectangle, the
    negative control). Each well-formed particle reads `pattern`, `mirrored`,
    `not_found` or `blank`; the fractions come with 95% intervals.

    Everything it needs comes from the folder -- the pattern from
    `pre/prediction.json`, the tip radius and E1's reference flat height from
    `during/instrument.json` -- and it refuses rather than substitutes when
    one is missing. It does not evaluate the gate.
    """
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.arms import RecordIncomplete
    from dobladillo.experiments.pattern import (
        SAMPLES,
        SampleResult,
        measure_sample,
        read_record,
        report_markdown,
        result,
    )
    from dobladillo.experiments.pattern import scans_for as pattern_scans
    from dobladillo.imaging.pattern import SPOT_SIGMA
    from dobladillo.imaging.readers import UnreadableScan
    from dobladillo.provenance import folder_chain, short

    emitter = Emitter(as_json)
    state = run_check(directory)
    try:
        record = read_record(directory)
    except RecordIncomplete as e:
        emitter.fail(str(e), kind=e.kind)
        return
    chain = state.chain
    if not chain.legacy and chain.scan_design != chain.predicted_design:
        emitter.fail(
            f"pre/prediction.json predicts design {short(chain.predicted_design)} but the "
            f"order in pre/order is of design {short(chain.scan_design)}: "
            + "; ".join(chain.problems or ("the two do not match",)),
            kind="design_mismatch" if chain.scan_design else "provenance_incomplete",
        )
        return

    scans = {sample: pattern_scans(directory, sample) for sample in SAMPLES}
    if not scans["pattern"]:
        emitter.fail(
            "no during/raw/pattern-* scans: name the patterned sample's files pattern-01.spm, "
            "... and E1's control control-01.spm, ... (see "
            "experiments/protocols/E8-patterned-rectangle.md)",
            kind="no_scans",
        )
        return
    measured: dict[str, SampleResult | None] = {}
    for sample, files in scans.items():
        if not files:
            measured[sample] = None
            continue
        try:
            measured[sample] = measure_sample(files, record)
        except UnreadableScan as e:
            emitter.fail(str(e), kind="unreadable_scan")
            return
    patterned = measured["pattern"]
    assert patterned is not None
    if not patterned.readings:
        emitter.fail(
            "no well-formed particle in a readable pattern-* scan"
            + (
                f"; skipped {len(patterned.skipped)} scan(s) as too coarse to read"
                if patterned.skipped
                else ""
            ),
            kind="no_particles",
        )
        return

    out = result(record, measured, spot_sigma=SPOT_SIGMA)
    out["record"] = state.as_dict()
    out["provenance"] = folder_chain(directory, scans=scans["pattern"]).as_dict()
    post = directory / "post"
    post.mkdir(exist_ok=True)
    (post / "pattern.json").write_text(json.dumps(out, indent=2) + "\n")
    report = post / "pattern.md"
    kept = ""
    if report.is_file() and "## Interpretation" in report.read_text():
        # The interpretation below the line is a person's, and survives a rerun.
        kept = report.read_text().split("## Interpretation", 1)[1].lstrip("\n")
    report.write_text(report_markdown(directory, out, state.problems) + kept)

    lines = ["designed, seen from the marked face:"]
    lines += [f"  {row}" for row in out["designed"]["pattern_seen_from_marked_face"]]
    for sample in SAMPLES:
        if out[sample] is None:
            lines.append(f"{sample}: no scans")
            continue
        summary = out[sample]["pattern"]
        found = summary["found"]
        marked = summary["found_among_marked"]
        lines.append(
            f"{sample}: {summary['read']} well-formed read  {summary['verdicts']}\n"
            f"  pattern either way round: {found['count']}/{found['total']} "
            f"({found['fraction']:.0%}, 95% {found['ci95'][0]:.0%}-{found['ci95'][1]:.0%})"
            f"   among particles showing marks: {marked['count']}/{marked['total']}"
        )
        for skipped in out[sample]["skipped"]:
            lines.append(f"  skipped {skipped['scan']}: {skipped['why']}")
    if "control_note" in out:
        lines.append(f"NOTE: {out['control_note']}")
    lines.append(f"wrote {post / 'pattern.json'} and {report}")
    lines += [f"RECORD: {p}" for p in state.problems]
    emitter.result({"directory": str(directory), **out}, f"{directory}\n" + "\n".join(lines))


@experiment_app.command("folding-screen")
def experiment_folding_screen(
    directory: Path = typer.Argument(..., help="An isothermal folding screen (E11) folder."),
    as_json: bool = JSON_OPTION,
) -> None:
    """E11: yield against temperature and time, from gel band intensities.

    Reads `during/gel_quant.csv` (one row per lane: time_min, temperature_c,
    folded_band, reference_band -- the reference being E1's standard ramp
    fold on the same gel). Writes `post/folding_screen.json`: the best
    temperature per time, the earliest time any temperature matches the ramp,
    and the measured window beside the predicted one. It judges nothing.
    """
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.arms import RecordIncomplete
    from dobladillo.experiments.folding_screen import read_quantification, summarise

    emitter = Emitter(as_json)
    state = run_check(directory)
    prediction_path = directory / "pre" / "prediction.json"
    predicted = None
    if prediction_path.is_file():
        predicted = json.loads(prediction_path.read_text()).get("folding_window")
    try:
        lanes = read_quantification(directory)
    except RecordIncomplete as e:
        emitter.fail(str(e), kind=e.kind)
        return
    result = summarise(lanes, predicted)
    result["prediction_preregistered"] = predicted is not None
    result["record"] = state.as_dict()
    post = directory / "post"
    post.mkdir(exist_ok=True)
    (post / "folding_screen.json").write_text(json.dumps(result, indent=2) + "\n")

    lines = []
    for row in result["by_time"]:
        good = row["as_good_as_ramp_c"]
        lines.append(
            f"{row['time_min']:>5g} min: best {row['best_temperature_c']:g} C "
            f"({row['best_relative_yield']:.0%} of the ramp)"
            + (f", as good as the ramp at {good[0]:g}-{good[1]:g} C" if good else "")
        )
    fastest = result["fastest_good_fold"]
    lines.append(
        f"fastest good fold: {fastest['time_min']:g} min at {fastest['best_temperature_c']:g} C"
        if fastest
        else "no lane reached the ramp's yield"
    )
    if predicted:
        tm = predicted["staple_tm_c"]
        lines.append(
            f"predicted staple Tm: median {tm['median']} C, 10-90% {tm['p10']}-{tm['p90']} C"
        )
    else:
        lines.append("RECORD: pre/prediction.json has no folding_window; nothing was predicted")
    lines += [f"RECORD: {p}" for p in state.problems]
    lines.append(f"wrote {post / 'folding_screen.json'}")
    emitter.result({"directory": str(directory), **result}, f"{directory}\n" + "\n".join(lines))


@experiment_app.command("check")
def experiment_check(
    directory: Path = typer.Argument(..., help="An experiment folder."),
    as_json: bool = JSON_OPTION,
) -> None:
    """What is missing, and whether the results can be believed.

    Exits non-zero when something is wrong with the record rather than with the
    science -- a missing prediction, or one recorded after the data.
    """
    from dobladillo.experiments import check as run_check

    emitter = Emitter(as_json)
    report = run_check(directory)
    payload = report.as_dict()
    rows: list[tuple[str, str]] = []
    for phase in report.phases:
        state = "complete" if phase.complete else ("started" if phase.started else "not started")
        detail = state if phase.complete else f"{state}, missing {', '.join(phase.missing)}"
        rows.append((str(phase.phase), detail))
    rows.append(("ready for", report.ready_for or "nothing: all three are complete"))
    if report.chain is not None:
        from dobladillo.provenance import short

        chain = report.chain
        rows.append(
            (
                "provenance",
                "no design hash recorded"
                if chain.legacy
                else f"design {short(chain.predicted_design)}, order "
                f"{short(chain.scan_design)}, {len(chain.scans)} raw file(s): "
                + ("verified" if chain.verified else "NOT verified"),
            )
        )
    for problem in report.problems:
        rows.append(("PROBLEM", problem))
    emitter.result(payload, f"{directory}\n" + _table(rows))
    if report.problems:
        raise typer.Exit(1)


# The experimentalist's acts: gate, lock, log, record, upload, commit. Each
# writes the record, so each is in mcp_server.FORBIDDEN_COMMANDS; the logic
# and the refusals live in `dobladillo.experiments.lifecycle`.


def _act(emitter: Emitter, act: Any) -> dict[str, Any] | None:
    """Run a lifecycle act; a refusal fails with its kind, never a traceback."""
    from dobladillo.experiments.lifecycle import Refused

    try:
        result: dict[str, Any] = act()
    except Refused as e:
        emitter.fail(str(e), kind=e.kind)
        return None
    return result


