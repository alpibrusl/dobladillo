REFERENCE_OPTION = typer.Option(
    "calibration-tile",
    "--reference",
    help="The reference's geometry: 'calibration-tile' (this project's tile, nominal) or "
    "a reference JSON written by `calibrate reference` or declared by hand.",
)


def _reference(spec: str, emitter: Emitter) -> Any:
    from dobladillo.calibration import reference as ref

    if spec == "calibration-tile":
        return ref.from_tile()
    path = Path(spec)
    if not path.is_file():
        emitter.fail(
            f"no reference {spec!r}: give 'calibration-tile' or a reference JSON file",
            kind="invalid_parameters",
        )
    try:
        return ref.load(path)
    except (ValueError, KeyError) as e:
        emitter.fail(f"{path}: not a usable reference: {e}", kind="invalid_parameters")


def _quantity_line(label: str, q: dict[str, Any], digits: int = 4) -> tuple[str, str]:
    return (label, f"{q['value']:.{digits}f} +- {q['U_k2']:.{digits}f} (k=2)")


@calibrate_app.command("reference")
def calibrate_reference(
    out: Path | None = typer.Option(None, "--out", help="Write the reference JSON here."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Write the calibration tile's reference geometry: its marks, in nm, with uncertainty.

    The positions are the DESIGN's (base pairs x rise along the helices,
    helices x inter-helix spacing across), so the reference is `nominal`: it
    calibrates X/Y ratio and skew on its own, and absolute scale only to the
    design's uncertainty, until a batch is certified (K8). To calibrate with
    another sample, write a JSON of the same schema from its datasheet.
    """
    from dobladillo.calibration.reference import from_tile

    emitter = Emitter(as_json)
    reference = from_tile()
    payload = reference.as_dict()
    if out is not None:
        reference.save(out)
        payload["written"] = str(out)
    rows = [
        ("reference", reference.name),
        ("status", reference.status),
        ("features", str(len(reference.features))),
        ("relative u (x, y)", ", ".join(f"{u:.2%}" for u in reference.relative_uncertainty)),
        ("traceable", str(reference.traceable).lower()),
    ]
    if out is not None:
        rows.append(("written", str(out)))
    emitter.result(payload, "calibration reference\n" + _table(rows))


@calibrate_app.command("lateral")
def calibrate_lateral_command(
    scans: list[Path] = typer.Argument(
        ..., help="Scans of the reference, all at the same scan size and settings."
    ),
    reference_spec: str = REFERENCE_OPTION,
    fixed_anisotropy: bool = typer.Option(
        False,
        "--fixed-anisotropy",
        help="Hold the reference's own y scale at nominal instead of fitting it. Only when "
        "its y dimension is certified, or the landing angles are too alike to separate it.",
    ),
    bootstrap: int = typer.Option(200, "--bootstrap", help="Bootstrap resamples over particles."),
    channel: str | None = typer.Option(None, "--channel", help="Height channel, if not default."),
    as_json: bool = JSON_OPTION,
) -> None:
    """The scanner's X and Y scale and skew, from reference particles at random angles.

    Mark centres, not outlines, are matched to the reference, so the tip's
    broadening does not bias the scale. The scanner's error is fixed in the
    image frame while each particle's own shape turns with it, which is what
    separates the two; the fit refuses when the particles' angles are too
    alike to do so. Every value carries a k=2 interval; `traceable` stays
    false unless the reference is certified.
    """
    from dobladillo.calibration.lateral import CalibrationRefused
    from dobladillo.calibration.payloads import lateral_payload
    from dobladillo.imaging.readers import UnreadableScan, read

    emitter = Emitter(as_json)
    reference = _reference(reference_spec, emitter)
    images = []
    for scan in scans:
        try:
            images.append(read(scan, channel=channel))
        except (UnreadableScan, OSError) as e:
            emitter.fail(f"{scan}: {e}", kind="unreadable_scan")
    try:
        payload, _ = lateral_payload(
            images,
            reference,
            fit_anisotropy=False if fixed_anisotropy else None,
            bootstrap=bootstrap,
        )
    except CalibrationRefused as e:
        emitter.fail(str(e), kind="calibration_refused")
        return
    payload["scans"] = [str(s) for s in scans]
    emitter.result(
        payload,
        f"lateral calibration against {reference.name}\n" + _table(_lateral_rows(payload)),
    )


def _lateral_rows(payload: dict[str, Any]) -> list[tuple[str, str]]:
    """`calibrate lateral`'s table, from its payload."""
    scanner, correction = payload["scanner"], payload["correction"]
    rejected = payload["rejected_particles"]
    return [
        _quantity_line("scale x (reported/true)", scanner["scale_x"]),
        _quantity_line("scale y (reported/true)", scanner["scale_y"]),
        _quantity_line("skew, deg", scanner["skew_deg"], 3),
        _quantity_line("correction x", correction["x"]),
        _quantity_line("correction y", correction["y"]),
        _quantity_line("reference y / nominal", payload["object_anisotropy"]),
        ("particles, features", f"{payload['n_particles']}, {payload['n_features']}"),
        ("rejected", ", ".join(f"{k} {v}" for k, v in sorted(rejected.items())) or "none"),
        ("traceable", str(payload["traceable"]).lower()),
        *(("WARNING", w) for w in payload.get("warnings", [])),
    ]


@calibrate_app.command("tip")
def calibrate_tip(
    scan: Path = typer.Argument(..., help="A scan with sharp features taller than the tip's apex."),
    size_px: int = typer.Option(31, "--size-px", help="Tip array size, odd, in pixels."),
    threshold_sigma: float | None = typer.Option(
        None,
        "--threshold-sigma",
        help="Noise tolerance in units of the image's pixel noise (default 5: below that, "
        "noise made the estimate sharper than the true tip in the tests).",
    ),
    feature_height_nm: float = typer.Option(
        2.0, "--feature-height", help="Height of the features the resolution is asked for, nm."
    ),
    out: Path | None = typer.Option(None, "--out", help="Write the full tip (heights) as JSON."),
    channel: str | None = typer.Option(None, "--channel", help="Height channel, if not default."),
    as_json: bool = JSON_OPTION,
) -> None:
    """The tip, reconstructed blind from the scan, its apex radius, and the resolution it allows.

    Villarrubia's blind reconstruction (J. Res. NIST 102, 425, 1997),
    implemented from the paper. The estimate is an OUTER bound: never sharper
    than the true tip, so widths corrected with it are corrected by at most
    the right amount. A scan without sharp features -- including a staircase
    of flat blocks -- cannot constrain the tip, and the result says so
    (`informative: false`) instead of quoting a radius.

    The noise threshold comes from the scan's own pixel noise, estimated from
    second differences along the fast axis, which cancel line offsets and the
    slopes of features, so a crowded field is measured too.
    """
    from dobladillo.calibration.payloads import tip_payload
    from dobladillo.imaging.readers import UnreadableScan, read

    emitter = Emitter(as_json)
    try:
        image = read(scan, channel=channel)
    except (UnreadableScan, OSError) as e:
        emitter.fail(f"{scan}: {e}", kind="unreadable_scan")
        return
    try:
        found = tip_payload(
            image,
            source=str(scan),
            size_px=size_px,
            threshold_sigma=threshold_sigma,
            feature_height_nm=feature_height_nm,
        )
    except ValueError as e:
        emitter.fail(str(e), kind="invalid_parameters")
        return
    payload, tip = found.payload, found.payload["tip"]
    if out is not None:
        out.write_text(
            json.dumps({**payload, "tip": {**tip, "heights_nm": found.heights_nm}}, indent=2)
        )
        payload["written"] = str(out)
    rows = _tip_rows(payload, feature_height_nm, found.sigma)
    if out is not None:
        rows.append(("written", str(out)))
    emitter.result(payload, f"tip from {scan.name}\n" + _table(rows))


def _tip_rows(
    payload: dict[str, Any], feature_height_nm: float, sigma: float
) -> list[tuple[str, str]]:
    """`calibrate tip`'s table, from its payload and the noise multiple it used."""
    noise, tip = payload["noise"], payload["tip"]
    radius, resolution = payload["apex_radius"], payload["resolution"]
    return [
        ("pixel noise, nm", f"{noise['sigma_nm']:.3f}"),
        ("threshold, nm", f"{tip['threshold_nm']:.3f} ({sigma:g} sigma)"),
        (
            "informative",
            str(tip["informative"]).lower() + (f" ({tip['note']})" if tip["note"] else ""),
        ),
        (
            "apex radius, nm",
            f"{radius['radius_nm']:.2f} +- {2 * radius['uncertainty_nm']:.2f} (k=2), an upper bound"
            if radius["determined"]
            else f"not determined: {radius['reason']}",
        ),
        (
            f"resolution for {feature_height_nm:g} nm features",
            f"{resolution['value_nm']:.2f} +- {2 * resolution['uncertainty_nm']:.2f} nm (k=2)"
            if resolution["resolvable"]
            else f"not determined: {resolution['reason']}",
        ),
    ]


@calibrate_app.command("drift")
def calibrate_drift(
    frames: list[Path] = typer.Argument(
        ...,
        help="Frames of the same field, in time order; or one high-speed movie (.asd, .h5-jpk).",
    ),
    interval_s: float | None = typer.Option(
        None,
        "--interval-s",
        help="Time between frames, s (evenly spaced frames). For a movie, replaces the file's.",
    ),
    times: str | None = typer.Option(
        None,
        "--times",
        help="Comma-separated frame times in s, instead of --interval-s. For a movie, "
        "replaces the file's.",
    ),
    channel: str | None = typer.Option(None, "--channel", help="Height channel, if not default."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Drift between frames: displacement per frame and a velocity with its standard error.

    Sub-pixel cross-correlation of each frame against the first. Only drift
    BETWEEN frames is measured, not the shear within one. Give several image
    files with --interval-s or --times, or ONE high-speed AFM movie (.asd,
    .h5-jpk), whose frame times come from the file unless --interval-s or
    --times replaces them; `times_source` in the output says which were used.
    A movie whose times cannot be trusted is refused, not guessed at.
    """
    from dobladillo.calibration.payloads import drift_payload
    from dobladillo.imaging.readers import MOVIES, UnreadableScan, read, read_stack, suffix_of

    emitter = Emitter(as_json)
    if interval_s is not None and times is not None:
        emitter.fail("give --interval-s or --times, not both", kind="invalid_parameters")
    given_times: list[float] | None = None
    if times is not None:
        try:
            given_times = [float(t) for t in times.split(",")]
        except ValueError:
            emitter.fail(f"could not read times from {times!r}", kind="invalid_parameters")
            return
    times_source = "--interval-s" if interval_s is not None else "--times" if times else "file"

    movies = [f for f in frames if suffix_of(f) in MOVIES]
    if movies:
        if len(frames) != 1:
            emitter.fail(
                "give one movie, or several image files; not several movies, nor a movie "
                f"with other files ({', '.join(str(m) for m in movies)})",
                kind="invalid_parameters",
            )
        try:
            stack = read_stack(
                frames[0], channel=channel, interval_s=interval_s, times_s=given_times
            )
        except (UnreadableScan, OSError) as e:
            emitter.fail(f"{frames[0]}: {e}", kind="unreadable_scan")
            return
        except ValueError as e:
            emitter.fail(str(e), kind="invalid_parameters")
            return
        images = list(stack.frames)
        times_s = list(stack.times_s)
        described = stack.describe()
        source: dict[str, Any] = {
            "movie": str(frames[0]),
            **{k: described[k] for k in ("instrument", "channel", "scan_direction")},
            "times_source": times_source,
            "file_frame_interval_s": stack.file_interval_s,
            "file_times_note": stack.times_note,
        }
    else:
        if interval_s is None and given_times is None:
            emitter.fail(
                "give --interval-s or --times: image files carry no frame times (only a "
                "movie, .asd or .h5-jpk, does)",
                kind="invalid_parameters",
            )
        if given_times is not None:
            times_s = given_times
        else:
            assert interval_s is not None
            times_s = [i * interval_s for i in range(len(frames))]
        if len(times_s) != len(frames):
            emitter.fail(
                f"{len(frames)} frames but {len(times_s)} times", kind="invalid_parameters"
            )
        images = []
        for frame in frames:
            try:
                images.append(read(frame, channel=channel))
            except (UnreadableScan, OSError) as e:
                emitter.fail(f"{frame}: {e}", kind="unreadable_scan")
        source = {"frame_files": [str(f) for f in frames], "times_source": times_source}
    try:
        payload = {**drift_payload(images, times_s), **source}
    except ValueError as e:
        emitter.fail(str(e), kind="invalid_parameters")
        return
    rows = _drift_rows(payload)
    rows.insert(1, ("times from", times_source))
    if movies and stack.times_source == "file":
        rows.append(("file times", stack.times_note))
    emitter.result(payload, "drift\n" + _table(rows))


def _drift_rows(payload: dict[str, Any]) -> list[tuple[str, str]]:
    """`calibrate drift`'s table, from its payload."""
    v = payload["velocity_nm_s"]
    return [
        ("frames", str(payload["frames"])),
        ("vx, nm/s", f"{v['x']:.4f} +- {2 * v['x_uncertainty']:.4f} (k=2)"),
        ("vy, nm/s", f"{v['y']:.4f} +- {2 * v['y_uncertainty']:.4f} (k=2)"),
        ("speed, nm/s", f"{v['speed']:.4f} +- {2 * v['speed_uncertainty']:.4f} (k=2)"),
        ("residual rms, nm", f"{payload['residual_rms_nm']:.3f}"),
    ]


@calibrate_app.command("report")
def calibrate_report(
    directory: Path = typer.Argument(..., help="A calibration (K) experiment folder."),
    bootstrap: int = typer.Option(200, "--bootstrap", help="Lateral: bootstrap resamples."),
    size_px: int = typer.Option(31, "--size-px", help="Tip: array size, odd, in pixels."),
    threshold_sigma: float | None = typer.Option(
        None, "--threshold-sigma", help="Tip: noise tolerance in pixel-noise units (default 5)."
    ),
    feature_height_nm: float = typer.Option(
        2.0, "--feature-height", help="Tip: height of the features the resolution is for, nm."
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Every calibration the folder's scans support; writes `post/calibration.json`.

    Finds the scans in `during/raw/` by name: `pattern-NN` and `overlap-NN`
    (lateral; one fit per subfolder, prefix and scan angle, never pooled),
    K4's `<block>-NN` such as `staircase/S1-01` (tip, each scan on its own),
    and `frame-NN` (drift, one series per subfolder). The conditions come
    from `during/instrument.json` -- scan angle, direction and closed loop,
    the deposition cations, the tip's part number, frame times -- and each
    analysis refuses, with its own `kind`, when one it depends on is not
    recorded; the others still run. The reference is the folder's part
    (`calibration-tile`) or the record's `calibration_reference`, never a
    default. Per analysis the result is the file-level command's payload,
    with the conditions and the scans' hashes. Exits 1 when any analysis was
    refused. It does not evaluate the gate.
    """
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.arms import RecordIncomplete
    from dobladillo.experiments.calibration import Options, run

    emitter = Emitter(as_json)
    options = Options(
        bootstrap=bootstrap,
        size_px=size_px,
        threshold_sigma=threshold_sigma,
        feature_height_nm=feature_height_nm,
    )
    try:
        out = run(directory, options)
    except RecordIncomplete as e:
        emitter.fail(str(e), kind=e.kind)
        return
    state = run_check(directory)
    out["record"] = state.as_dict()
    post = directory / "post"
    post.mkdir(exist_ok=True)
    written = post / "calibration.json"
    written.write_text(json.dumps(out, indent=2) + "\n")

    rows: list[tuple[str, str]] = []
    for analysis, block in out["analyses"].items():
        if block["status"] == "no_data":
            rows.append((analysis, "no scans named for it"))
            continue
        for entry in block["results"]:
            name = entry.get("set") or entry.get("scan") or entry.get("series")
            label = f"{analysis} {name}"
            if "refused" in entry:
                rows.append((label, f"REFUSED {entry['refused']['kind']}"))
                continue
            result = entry["result"]
            if analysis == "lateral":
                s = result["scanner"]
                rows.append(
                    (
                        label,
                        f"scale x {s['scale_x']['value']:.4f} +- {s['scale_x']['U_k2']:.4f}, "
                        f"y {s['scale_y']['value']:.4f} +- {s['scale_y']['U_k2']:.4f}, "
                        f"skew {s['skew_deg']['value']:.3f} +- {s['skew_deg']['U_k2']:.3f} deg "
                        f"(k=2; {result['n_particles']} particles)",
                    )
                )
            elif analysis == "tip":
                r = result["apex_radius"]
                rows.append(
                    (
                        label,
                        f"apex {r['radius_nm']:.2f} +- {2 * r['uncertainty_nm']:.2f} nm (k=2), "
                        "an upper bound"
                        if r["determined"]
                        else f"apex not determined: {r['reason']}",
                    )
                )
            else:
                v = result["velocity_nm_s"]
                rows.append(
                    (
                        label,
                        f"{result['frames']} frames, speed {v['speed']:.4f} +- "
                        f"{2 * v['speed_uncertainty']:.4f} nm/s (k=2)",
                    )
                )
    rows.append(("wrote", str(written)))
    rows += [
        ("REFUSED", f"{r['analysis']} {r['of']}: {r['kind']}: {r['message']}")
        for r in out["refusals"]
    ]
    rows += [("RECORD", p) for p in state.problems]
    emitter.result({"directory": str(directory), **out}, f"{directory}\n" + _table(rows))
    if out["refusals"]:
        raise typer.Exit(1)


