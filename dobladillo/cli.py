@app.command("compare")
def compare_command(
    part: str = PART_ARGUMENT,
    run_dir: Path | None = typer.Option(None, "--run", help="A finished oxDNA run directory."),
    scan: Path | None = typer.Option(
        None, "--scan", help="An AFM scan of the same part: native or .gsf."
    ),
    tip_radius: float = typer.Option(
        ...,
        help="Tip apex radius, nm, MEASURED not nominal. No default on purpose: it "
        "enters every width as a square root and a plausible guess produces a "
        "plausible wrong answer. Prefer `dobladillo experiment report`, which reads "
        "it from the session record.",
    ),
    magnesium_mm: float = typer.Option(12.0, help="Mg2+ in the imaging buffer, mM."),
    scan_temperature_c: float = typer.Option(23.0, help="Temperature the scan was taken at."),
    skip: int = typer.Option(0, help="Frames to discard as equilibration."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Design against simulation against measurement: the closed loop.

    Supply whichever of `--run` and `--scan` exist; with neither, this reports
    the designed dimensions and says so rather than pretending to compare.

    Most of what this does is refuse. A designed length, a simulated extent and
    an AFM footprint are three different quantities, and the difference between
    the last two is dominated by tip radius rather than by anything about the
    structure. Reconciling them is the work; the leftover is the result.
    """
    from dobladillo.compare import Conditions, Observation, compare, deconvolve_tip, designed
    from dobladillo.readings import Measured

    emitter = Emitter(as_json)
    built = _make_part(part, emitter)
    design = built.as_dict()
    dimensions = design.get("approx_dimensions_nm") or design["approx_arm_dimensions_nm"]
    # Longest first, so design, simulation and measurement are ordered alike.
    ordered = sorted(dimensions.items(), key=lambda kv: -float(kv[1]))
    quantities = [("length_nm", ordered[0][1]), ("width_nm", ordered[-1][1])]

    observations: dict[str, list[Any]] = {q: [designed(q, float(v))] for q, v in quantities}

    if run_dir is not None:
        from dobladillo.analysis.observables import analyse
        from dobladillo.analysis.runs import NotAResult, load_run, production_trajectory

        try:
            frames, check = load_run(run_dir, skip=skip)
        except NotAResult as e:
            emitter.fail(str(e), kind="not_a_result")
            return
        from dobladillo.provenance import design_sha256, short

        # A run of another design -- an older tiling, a different joint -- is
        # a comparison of two objects. Refuse on a recorded mismatch; a run
        # older than the record carries no hash, and that is said, not hidden.
        run_design = (check.metadata.get("provenance") or {}).get("design_sha256")
        if run_design is None:
            emitter.note(
                "note: this run's metadata records no design hash, so nothing checks "
                f"that it is a run of the current {part}"
            )
        elif run_design != design_sha256(built.design):
            emitter.fail(
                f"the run is of design {short(run_design)}, but {part} is now design "
                f"{short(design_sha256(built.design))}: comparing them compares two objects",
                kind="design_mismatch",
            )
            return
        report = analyse(frames, trajectory=production_trajectory(run_dir), skip=skip)
        salt = check.metadata.get("model", {}).get("salt_concentration_m")
        conditions = Conditions(temperature_c=20.0, sodium_m=salt, model="oxDNA2")
        for quantity, key in (("length_nm", "longest"), ("width_nm", "middle")):
            spread = report.dimensions_nm[key]
            observations[quantity].append(
                Observation(
                    quantity=quantity,
                    value_nm=spread.mean,
                    definition="simulated_extent",
                    origin="simulated",
                    conditions=conditions,
                    uncertainty_nm=spread.sd,
                    # Frames, not independent samples: MD frames are correlated
                    # and the effective size is smaller, so this understates the
                    # error. Stated here rather than silently assumed away.
                    n=spread.n,
                    note="" if not report.undersampled else "undersampled trajectory",
                )
            )

    if scan is not None:
        from dobladillo.imaging.classify import population
        from dobladillo.imaging.flatten import flatten
        from dobladillo.imaging.particles import find_particles
        from dobladillo.imaging.readers import UnreadableScan, read

        try:
            image = read(scan)
        except UnreadableScan as e:
            emitter.fail(str(e), kind="unreadable_scan")
            return
        flattened, background = flatten(image)
        particles = [p for p in find_particles(flattened, background) if not p.touches_edge]
        if not particles:
            emitter.fail("no particles clear of the frame edge in that scan", kind="no_particles")
            return
        import statistics

        conditions = Conditions(
            temperature_c=scan_temperature_c,
            magnesium_m=magnesium_mm / 1000.0,
            model="AFM, half-height footprint",
        )
        heights = [p.height_nm for p in particles]
        median_height = statistics.median(heights)
        for quantity, attribute in (("length_nm", "length_nm"), ("width_nm", "width_nm")):
            values = [getattr(p, attribute) for p in particles]
            raw = Observation(
                quantity=quantity,
                value_nm=statistics.fmean(values),
                definition="afm_half_height",
                origin="measured",
                conditions=conditions,
                uncertainty_nm=statistics.stdev(values) if len(values) > 1 else None,
                n=len(values),
            )
            observations[quantity].append(
                deconvolve_tip(
                    raw,
                    feature_height_nm=median_height,
                    # The flag demands a measured value, so the operator is
                    # asserting one. Recorded as exactly that: stated, with
                    # no instrument, rather than read from a session record.
                    tip_radius_nm=Measured.stated(
                        tip_radius, "tip_radius", source="--tip-radius on the command line"
                    ),
                ).observation
            )
        population(particles, length_nm=quantities[0][1], width_nm=quantities[1][1], height_nm=2.0)

    results = {q: compare(q, obs) for q, obs in observations.items()}
    payload = {
        "part": part,
        "design_sha256": _design_hash(built.design),
        "sources": {
            "designed": True,
            "simulated": run_dir is not None and str(run_dir),
            "measured": scan is not None and str(scan),
        },
        "tip_radius_nm": tip_radius,
        "comparisons": {q: c.as_dict() for q, c in results.items()},
        "agrees": all(c.agrees for c in results.values()),
        "compared_anything": any(c.compared_anything for c in results.values()),
    }
    body = "\n\n".join(c.summary() for c in results.values())
    if not payload["compared_anything"]:
        body += "\n\nNothing was compared. Supply --run, --scan, or both."
    emitter.result(payload, f"closed loop: {part}\n" + body)


@app.command("export")
def export_command(
    part: str = PART_ARGUMENT,
    experiment: Path | None = typer.Option(
        None,
        "--experiment",
        help="An experiment folder of this part. Its protocols, and its comparison once "
        "post/ is complete, go in -- only if its provenance chain names this design.",
    ),
    out: Path = typer.Option(Path("exports"), "--out", help="Directory to write the zip into."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Write a local archive of a part in Nanobase's layout. Never uploads.

    Design files, oxDNA topology and configuration, an idealised image and a
    record of Nanobase's three upload forms, validated as it is written. A
    person may deposit it later through Nanobase's own form; this command
    talks to nothing but the disk. See `dobladillo.export` for the layout
    and the public documentation it was taken from.
    """
    from dobladillo.export import ExportRefused, export_part

    emitter = Emitter(as_json)
    built = _make_part(part, emitter)
    if experiment is not None and not (experiment / "pre").is_dir():
        emitter.fail(f"{experiment} is not an experiment folder", kind="missing_directory")
        return
    try:
        result = export_part(
            part=part, design=built.design, info=built.as_dict(), out=out, experiment=experiment
        )
    except ExportRefused as e:
        emitter.fail(str(e), kind=e.kind)
        return
    payload = result.as_dict()
    rows = [
        ("wrote", str(result.path)),
        ("sha256", result.sha256),
        ("design", payload["provenance"]["design_sha256"][:8]),
    ]
    rows += [(category, f"{n} file(s)") for category, n in payload["files"].items() if n]
    rows += [(f"not included: {k}", v) for k, v in payload["not_included"].items()]
    rows.append(("valid", "yes" if result.valid else f"NO, {len(result.problems)} problems"))
    rows.append(("uploaded", "no -- dobladillo never uploads"))
    body = f"{part}: export\n" + _table(rows)
    for problem in result.problems:
        body += f"\n  PROBLEM  {problem}"
    emitter.result(payload, body)
    if not result.valid:
        raise typer.Exit(1)


@app.command("export-check")
def export_check_command(
    archive: Path = typer.Argument(..., help="A zip written by `dobladillo export`."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Validate an export archive against its layout. Exits non-zero if it departs."""
    from dobladillo.export import LAYOUT, validate
    from dobladillo.provenance import file_sha256

    emitter = Emitter(as_json)
    if not archive.is_file():
        emitter.fail(f"no such file: {archive}", kind="missing_file", code=2)
        return
    problems = validate(archive)
    payload = {
        "archive": str(archive),
        "sha256": file_sha256(archive),
        "layout": LAYOUT,
        "valid": not problems,
        "problems": problems,
    }
    body = f"{archive}\n" + _table([("layout", LAYOUT), ("valid", "yes" if not problems else "NO")])
    for problem in problems:
        body += f"\n  PROBLEM  {problem}"
    emitter.result(payload, body)
    if problems:
        raise typer.Exit(1)


