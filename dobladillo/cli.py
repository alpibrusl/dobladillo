@experiment_app.command("new")
def experiment_new(
    slug: str = typer.Argument(..., help="Folder name. Start it with the date: 2026-09-22-..."),
    part: str = typer.Option("rectangle", help="Which part this experiment is about."),
    root: Path = EXPERIMENTS_ROOT,
    plate: int = typer.Option(96, help="Well plate format for the order."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Scaffold an experiment, with its predictions recorded up front.

    The predictions are the point. `post/` compares against what is written
    here, not against whatever the toolchain predicts later, so an experiment
    stays honest when a part's defaults change -- and `experiment check` says
    so if this file turns out to be newer than the data.

    Commit `pre/` before taking any data. That commit is what makes the
    ordering evidence rather than an assertion.
    """
    from dobladillo import provenance
    from dobladillo.experiments import scaffold

    emitter = Emitter(as_json)
    built = _make_part(part, emitter)
    design = built.as_dict()
    dimensions = design.get("approx_dimensions_nm") or design["approx_arm_dimensions_nm"]
    ordered = sorted((float(v) for v in dimensions.values()), reverse=True)
    # The design's identity, taken before the order labels any strand. Every
    # later link -- the order manifest, each scan, the comparison -- names it.
    design_hash = provenance.design_sha256(built.design)

    prediction = {
        "part": part,
        "generated_by": f"dobladillo {__version__}",
        "provenance": provenance.design_record(design_hash, part=part),
        "predicted_nm": {
            "length": round(ordered[0], 1),
            "width": round(ordered[-1], 1),
            "height": 2.0 * design.get("layers", 1),
        },
        "design": design,
        "gate": {
            "criterion": "FILL THIS IN BEFORE TAKING DATA",
            "note": "What result would make this experiment a failure? Write it here "
            "first. A gate decided afterwards is a description of the data.",
        },
    }

    plan = _experiment_plan(slug=slug, part=part, prediction=prediction)
    from dobladillo.lab.protocol import folding_protocol

    sheet = folding_protocol(
        part_name=part,
        dimensionality="2D" if design["lattice"] == "square" else "3D",
        scaffold_variant=design["scaffold"]["variant"],
    )
    protocol_text = _protocol_markdown(part, sheet)

    try:
        directory = scaffold(
            root, slug=slug, prediction=prediction, plan=plan, protocol=protocol_text
        )
    except FileExistsError as e:
        emitter.fail(str(e), kind="already_exists")
        return

    # Wells must be assigned before the plate workbook can be written; the
    # bulk CSV does not need them, which is why forgetting produces one file
    # and half an error.
    from dobladillo.lab import plates as lab

    layout = lab.name_and_assign_wells(built.design, plate_type=plate)
    written = lab.write_order_files(
        built.design, directory=directory / "pre" / "order", name=part, plate_type=plate
    )
    (directory / "pre" / "order" / "pipetting.json").write_text(
        json.dumps(lab.pipetting_sheet(layout), indent=2) + "\n"
    )
    manifest = provenance.write_order_manifest(
        directory / "pre" / "order",
        name=part,
        part=part,
        design_hash=design_hash,
        files=[*written.values(), directory / "pre" / "order" / "pipetting.json"],
    )

    payload = {
        "directory": str(directory),
        "part": part,
        "design_sha256": design_hash,
        "prediction": prediction["predicted_nm"],
        "order_files": {k: str(v) for k, v in written.items()},
        "order_manifest": str(manifest),
        "next": "Fill in pre/plan.md's gate, then COMMIT pre/ before taking data.",
    }
    rows = [
        ("created", str(directory)),
        ("part", part),
        (
            "predicted",
            f"{prediction['predicted_nm']['length']} x {prediction['predicted_nm']['width']} nm",
        ),
        ("design", provenance.short(design_hash)),
    ]
    rows += [(f"order {k}", str(v)) for k, v in written.items()]
    rows.append(("next", "fill in the gate in pre/plan.md, then commit pre/"))
    emitter.result(payload, "experiment\n" + _table(rows))


@experiment_app.command("report")
def experiment_report(
    directory: Path = typer.Argument(..., help="An experiment folder."),
    scans: list[Path] | None = typer.Option(
        None,
        "--scan",
        help="A scan to include: native or .gsf. Repeatable. Defaults to every native "
        "image file in during/raw, or every .gsf if there are none.",
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Measure the scans and compare them against what was predicted.

    Writes `post/`. Everything it needs comes from the folder: the part and the
    predictions from `pre/prediction.json`, the tip radius from
    `during/instrument.json`.

    It refuses rather than substitutes. A missing tip radius stops the report,
    because the alternative is a number that looks like a measurement -- 8.7 nm
    on a 2 nm plate with a 10 nm tip, a quarter of a 36 nm width -- and nothing
    downstream could tell.
    """
    import statistics

    from dobladillo.compare import Conditions, Observation, compare, deconvolve_tip, designed
    from dobladillo.compare.corrections import half_height_broadening_nm
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.instrument import read_instrument
    from dobladillo.imaging.classify import population
    from dobladillo.imaging.flatten import flatten
    from dobladillo.imaging.particles import find_particles
    from dobladillo.imaging.readers import UnreadableScan, is_native_image, read
    from dobladillo.readings import combine

    emitter = Emitter(as_json)
    state = run_check(directory)

    prediction_path = directory / "pre" / "prediction.json"
    if not prediction_path.is_file():
        emitter.fail(
            "no pre/prediction.json: there is nothing this experiment could be "
            "compared against. It cannot be written now -- see experiments/README.md.",
            kind="no_prediction",
        )
        return
    prediction = json.loads(prediction_path.read_text())

    # Provenance, before anything is measured. A prediction that names its
    # design must be tested against scans of that design, and the scans'
    # design is the design of the order the sample was folded from. A legacy
    # prediction names no design: that is a record problem, already in
    # `state.problems`, and the report goes ahead and says so.
    chain = state.chain
    if not chain.legacy:
        from dobladillo.provenance import short

        if chain.scan_design is None:
            emitter.fail(
                f"pre/prediction.json is of design {short(chain.predicted_design)}, but which "
                "design the scans are of cannot be established: "
                + "; ".join(chain.problems or ("pre/order has no manifest",)),
                kind="provenance_incomplete",
            )
            return
        if chain.scan_design != chain.predicted_design:
            emitter.fail(
                f"the scans are of design {short(chain.scan_design)} (the design pre/order "
                f"was made from) but pre/prediction.json predicts design "
                f"{short(chain.predicted_design)}. Comparing them would test a prediction "
                "against a different object. Scaffold a new experiment for the new design",
                kind="design_mismatch",
            )
            return

    # The one place this command touches instrument.json: readings come back
    # typed, so the nominal radius on the box cannot reach the correction.
    try:
        instrument = read_instrument(directory)
    except ValueError as e:
        emitter.fail(f"during/instrument.json: {e}", kind="invalid_reading")
        return
    if instrument is None:
        emitter.fail("no during/instrument.json", kind="no_instrument")
        return
    before, after = instrument.tip["before"], instrument.tip["after"]
    if before is None:
        emitter.fail(
            "during/instrument.json has no measured tip radius. This is not a field to "
            "fill in with the nominal value: a nominal 10 nm tip is routinely 8-20 nm "
            "in use, the correction goes as sqrt(R), and guessing it wrong turns an "
            "agreement into a disagreement or the reverse. Measure it, or say in "
            "post/report.md that widths are uncorrected.",
            kind="no_tip_radius",
        )
        return
    # A tip that blunted mid-session makes early and late scans differently
    # wrong. The spread between before and after is real information about how
    # well the correction is known, so `combine` carries it as the reading's
    # uncertainty and `deconvolve_tip` widens the result by it, rather than
    # averaging it away silently.
    tip = combine(
        [r for r in (before, after) if r is not None],
        "tip_radius",
        source="mean of during/instrument.json: tip.measured_radius_before_nm, _after_nm",
    )
    tip_radius = tip.value
    blunting = (tip.uncertainty or 0.0) / tip_radius

    # Every scan by default, because the experiments count particles across
    # many images: E1 asks for 300, and one 2 x 2 um overview holds about 40.
    # This used to insist on exactly one file, so a student following the
    # protocol would have reported a yield from an eighth of their data.
    if not scans:
        # Native files first, and never native and .gsf together: an export
        # is a copy of an image already in the folder, and reading both would
        # count every particle twice. Force maps are not overview images and
        # are left out of the default.
        raw_dir = directory / "during" / "raw"
        files = sorted(raw_dir.iterdir()) if raw_dir.is_dir() else []
        native = [p for p in files if p.is_file() and is_native_image(p)]
        exports = [p for p in files if p.suffix.lower() == ".gsf"]
        scans = native or exports
        if native and exports:
            emitter.note(
                f"reading the {len(native)} native files in during/raw and not the "
                f"{len(exports)} .gsf exports beside them, which are copies of the same "
                "images. Pass --scan to choose."
            )
        if not scans:
            emitter.fail(
                "no scans in during/raw: put the instrument's own files there "
                "(see experiments/protocols/common-techniques.md)",
                kind="no_scans",
            )
            return

    all_particles = []
    for scan in scans:
        try:
            image = read(scan)
        except UnreadableScan as e:
            emitter.fail(f"{scan.name}: {e}", kind="unreadable_scan")
            return
        flattened, background = flatten(image)
        all_particles.extend(find_particles(flattened, background))
    particles = [p for p in all_particles if not p.touches_edge]
    if not particles:
        emitter.fail("no particles clear of the frame edge", kind="no_particles")
        return

    from dobladillo.provenance import folder_chain

    # Re-read with exactly the scans measured, so each is hashed and named.
    chain = folder_chain(directory, scans=list(scans))

    predicted = prediction["predicted_nm"]
    magnesium, temperature = instrument.magnesium, instrument.temperature
    conditions = Conditions(
        temperature_c=temperature.value if temperature else None,
        magnesium_m=magnesium.value / 1000.0 if magnesium and magnesium.value else None,
        model="AFM, half-height footprint",
    )
    median_height = statistics.median([p.height_nm for p in particles])
    results = {}
    for quantity, attribute in (("length", "length_nm"), ("width", "width_nm")):
        values = [getattr(p, attribute) for p in particles]
        raw = Observation(
            quantity=f"{quantity}_nm",
            value_nm=statistics.fmean(values),
            definition="afm_half_height",
            origin="measured",
            conditions=conditions,
            uncertainty_nm=statistics.stdev(values) if len(values) > 1 else None,
            n=len(values),
        )
        corrected = deconvolve_tip(
            raw,
            feature_height_nm=median_height,
            tip_radius_nm=tip,
        ).observation
        results[quantity] = compare(
            f"{quantity}_nm",
            [designed(f"{quantity}_nm", float(predicted[quantity])), corrected],
        )

    # Classify against what the IMAGE should show -- the object plus the tip --
    # not against the object. Comparing them directly marks every good particle
    # malformed: `afm measure` had this bug and was fixed, and this command kept
    # it, so a correct E1 run would have reported a yield near zero.
    widening = 2 * half_height_broadening_nm(
        tip_radius_nm=tip_radius, feature_height_nm=median_height
    )
    found = population(
        all_particles,
        length_nm=float(predicted["length"]) + widening,
        width_nm=float(predicted["width"]) + widening,
        height_nm=float(predicted.get("height", 2.0)),
    )

    post = directory / "post"
    post.mkdir(exist_ok=True)
    measurements = {
        "scans": [str(x) for x in scans],
        "particles": len(particles),
        "tip_widening_nm": round(widening, 2),
        "tip_radius_nm": tip_radius,
        "tip_blunting_fraction": round(blunting, 3),
        "tip_radius": tip.as_dict(),
        "median_height_nm": round(median_height, 2),
        "population": found.as_dict(),
    }
    comparison = {
        "predicted_from": str(prediction_path),
        "predicted_nm": predicted,
        "record": state.as_dict(),
        "comparisons": {k: v.as_dict() for k, v in results.items()},
        "agrees": all(v.agrees for v in results.values()),
        "provenance": chain.as_dict(),
    }
    (post / "measurements.json").write_text(json.dumps(measurements, indent=2) + "\n")
    (post / "comparison.json").write_text(json.dumps(comparison, indent=2) + "\n")
    (post / "report.md").write_text(
        _post_report(
            directory=directory,
            state=state,
            measurements=measurements,
            results=results,
            chain=chain,
        )
    )

    payload = {
        "directory": str(directory),
        **comparison,
        "files": [
            str(post / "measurements.json"),
            str(post / "comparison.json"),
            str(post / "report.md"),
        ],
    }
    body = "\n\n".join(c.summary() for c in results.values())
    if state.problems:
        body += "\n\n" + "\n".join(f"RECORD: {p}" for p in state.problems)
    emitter.result(payload, f"{directory}\n" + body)


@experiment_app.command("compare-arms")
def experiment_compare_arms(
    directory: Path = typer.Argument(..., help="A paired (E2) experiment folder."),
    x_scans: list[Path] | None = typer.Option(
        None, "--x", help="A scan of sample X. Repeatable. Defaults to during/raw/X-*.gsf."
    ),
    y_scans: list[Path] | None = typer.Option(
        None, "--y", help="A scan of sample Y. Repeatable. Defaults to during/raw/Y-*.gsf."
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Compare two blinded arms by flat fraction, and state the verdict both ways.

    Writes `post/arms.json`. The samples are known only as X and Y, so this
    never asks which arm is corrected: it reports X - Y with a 95% Newcombe
    interval and what that would mean under either unblinding.

    Everything it needs comes from the folder -- per-arm tip radii from the
    before, between and after readings in `during/instrument.json`, the
    reference flat-sheet height from the same file -- and it refuses rather
    than substitutes when one is missing. Exits 1 when either arm has fewer
    than 100 counted particles, which the gate requires.
    """
    from dobladillo.experiments import check as run_check
    from dobladillo.experiments.arms import (
        ARMS,
        MIN_PER_ARM,
        RecordIncomplete,
        compare_blinded,
        measure_arm,
        read_record,
        result,
        scans_for,
    )
    from dobladillo.imaging.readers import UnreadableScan

    emitter = Emitter(as_json)
    state = run_check(directory)
    try:
        record = read_record(directory)
    except RecordIncomplete as e:
        emitter.fail(str(e), kind=e.kind)
        return

    given = {"X": x_scans, "Y": y_scans}
    measured = {}
    for arm in ARMS:
        scans = given[arm] or scans_for(directory, arm)
        if not scans:
            emitter.fail(
                f"no scans of {arm}: expected during/raw/{arm}-*.gsf, exported next to "
                "the native files (see experiments/protocols/E2-twist-pair.md)",
                kind="no_scans",
            )
            return
        try:
            measured[arm] = measure_arm(
                scans,
                tip_radius=record.tip_radius[arm],
                reference_height_nm=record.reference_height_nm,
                length_nm=record.length_nm,
                width_nm=record.width_nm,
            )
        except UnreadableScan as e:
            emitter.fail(str(e), kind="unreadable_scan")
            return
        except RecordIncomplete as e:
            emitter.fail(str(e), kind=e.kind)
            return

    comparison = compare_blinded(measured["X"], measured["Y"])
    arms = result(record, measured, comparison)
    arms["record"] = state.as_dict()
    post = directory / "post"
    post.mkdir(exist_ok=True)
    (post / "arms.json").write_text(json.dumps(arms, indent=2) + "\n")

    low, high = comparison.ci95
    lines = [
        f"{arm}: {arms[arm]['counts'].get('well_formed', 0)}/{arms[arm]['total']} flat "
        f"({arms[arm]['flat_fraction']:.0%})   tip {arms[arm]['tip_radius_nm']:.1f} nm"
        f"   counts {arms[arm]['counts']}"
        for arm in ARMS
    ]
    lines += [
        f"difference X - Y: {comparison.difference:+.0%}   95% [{low:+.0%}, {high:+.0%}]",
        f"if X is the corrected arm:  {arms['verdict_if_x_is_corrected']}",
        f"if Y is the corrected arm:  {arms['verdict_if_y_is_corrected']}",
        f"wrote {post / 'arms.json'}",
    ]
    lines += [f"RECORD: {p}" for p in state.problems]
    emitter.result({"directory": str(directory), **arms}, f"{directory}\n" + "\n".join(lines))
    if arms["too_few_particles"]:
        emitter.note(
            f"fewer than {MIN_PER_ARM} counted particles in "
            f"{', '.join(arms['too_few_particles'])}; the gate requires at least that "
            "many per arm. Image more before interpreting this."
        )
        raise typer.Exit(1)


@experiment_app.command("check")
def experiment_check(
    directory: Path = typer.Argument(..., help="An experiment folder."),
    as_json: bool = JSON_OPTION,
) -> None:
    """What is missing, and whether the results can be believed.

    Exits non-zero when something is wrong with the record rather than with the
    science -- a missing prediction, or one recorded after the data.
    """
    from dobladillo.experiments import check as run_check

    emitter = Emitter(as_json)
    report = run_check(directory)
    payload = report.as_dict()
    rows: list[tuple[str, str]] = []
    for phase in report.phases:
        state = "complete" if phase.complete else ("started" if phase.started else "not started")
        detail = state if phase.complete else f"{state}, missing {', '.join(phase.missing)}"
        rows.append((str(phase.phase), detail))
    rows.append(("ready for", report.ready_for or "nothing: all three are complete"))
    if report.chain is not None:
        from dobladillo.provenance import short

        chain = report.chain
        rows.append(
            (
                "provenance",
                "no design hash recorded"
                if chain.legacy
                else f"design {short(chain.predicted_design)}, order "
                f"{short(chain.scan_design)}, {len(chain.scans)} raw file(s): "
                + ("verified" if chain.verified else "NOT verified"),
            )
        )
    for problem in report.problems:
        rows.append(("PROBLEM", problem))
    emitter.result(payload, f"{directory}\n" + _table(rows))
    if report.problems:
        raise typer.Exit(1)


@app.command("compare")
def compare_command(
    part: str = PART_ARGUMENT,
    run_dir: Path | None = typer.Option(None, "--run", help="A finished oxDNA run directory."),
    scan: Path | None = typer.Option(
        None, "--scan", help="An AFM scan of the same part: native or .gsf."
    ),
    tip_radius: float = typer.Option(
        ...,
        help="Tip apex radius, nm, MEASURED not nominal. No default on purpose: it "
        "enters every width as a square root and a plausible guess produces a "
        "plausible wrong answer. Prefer `dobladillo experiment report`, which reads "
        "it from the session record.",
    ),
    magnesium_mm: float = typer.Option(12.0, help="Mg2+ in the imaging buffer, mM."),
    scan_temperature_c: float = typer.Option(23.0, help="Temperature the scan was taken at."),
    skip: int = typer.Option(0, help="Frames to discard as equilibration."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Design against simulation against measurement: the closed loop.

    Supply whichever of `--run` and `--scan` exist; with neither, this reports
    the designed dimensions and says so rather than pretending to compare.

    Most of what this does is refuse. A designed length, a simulated extent and
    an AFM footprint are three different quantities, and the difference between
    the last two is dominated by tip radius rather than by anything about the
    structure. Reconciling them is the work; the leftover is the result.
    """
    from dobladillo.compare import Conditions, Observation, compare, deconvolve_tip, designed
    from dobladillo.readings import Measured

    emitter = Emitter(as_json)
    built = _make_part(part, emitter)
    design = built.as_dict()
    dimensions = design.get("approx_dimensions_nm") or design["approx_arm_dimensions_nm"]
    # Longest first, so design, simulation and measurement are ordered alike.
    ordered = sorted(dimensions.items(), key=lambda kv: -float(kv[1]))
    quantities = [("length_nm", ordered[0][1]), ("width_nm", ordered[-1][1])]

    observations: dict[str, list[Any]] = {q: [designed(q, float(v))] for q, v in quantities}

    if run_dir is not None:
        from dobladillo.analysis.observables import analyse
        from dobladillo.analysis.runs import NotAResult, load_run, production_trajectory

        try:
            frames, check = load_run(run_dir, skip=skip)
        except NotAResult as e:
            emitter.fail(str(e), kind="not_a_result")
            return
        from dobladillo.provenance import design_sha256, short

        # A run of another design -- an older tiling, a different joint -- is
        # a comparison of two objects. Refuse on a recorded mismatch; a run
        # older than the record carries no hash, and that is said, not hidden.
        run_design = (check.metadata.get("provenance") or {}).get("design_sha256")
        if run_design is None:
            emitter.note(
                "note: this run's metadata records no design hash, so nothing checks "
                f"that it is a run of the current {part}"
            )
        elif run_design != design_sha256(built.design):
            emitter.fail(
                f"the run is of design {short(run_design)}, but {part} is now design "
                f"{short(design_sha256(built.design))}: comparing them compares two objects",
                kind="design_mismatch",
            )
            return
        report = analyse(frames, trajectory=production_trajectory(run_dir), skip=skip)
        salt = check.metadata.get("model", {}).get("salt_concentration_m")
        conditions = Conditions(temperature_c=20.0, sodium_m=salt, model="oxDNA2")
        for quantity, key in (("length_nm", "longest"), ("width_nm", "middle")):
            spread = report.dimensions_nm[key]
            observations[quantity].append(
                Observation(
                    quantity=quantity,
                    value_nm=spread.mean,
                    definition="simulated_extent",
                    origin="simulated",
                    conditions=conditions,
                    uncertainty_nm=spread.sd,
                    # Frames, not independent samples: MD frames are correlated
                    # and the effective size is smaller, so this understates the
                    # error. Stated here rather than silently assumed away.
                    n=spread.n,
                    note="" if not report.undersampled else "undersampled trajectory",
                )
            )

    if scan is not None:
        from dobladillo.imaging.classify import population
        from dobladillo.imaging.flatten import flatten
        from dobladillo.imaging.particles import find_particles
        from dobladillo.imaging.readers import UnreadableScan, read

        try:
            image = read(scan)
        except UnreadableScan as e:
            emitter.fail(str(e), kind="unreadable_scan")
            return
        flattened, background = flatten(image)
        particles = [p for p in find_particles(flattened, background) if not p.touches_edge]
        if not particles:
            emitter.fail("no particles clear of the frame edge in that scan", kind="no_particles")
            return
        import statistics

        conditions = Conditions(
            temperature_c=scan_temperature_c,
            magnesium_m=magnesium_mm / 1000.0,
            model="AFM, half-height footprint",
        )
        heights = [p.height_nm for p in particles]
        median_height = statistics.median(heights)
        for quantity, attribute in (("length_nm", "length_nm"), ("width_nm", "width_nm")):
            values = [getattr(p, attribute) for p in particles]
            raw = Observation(
                quantity=quantity,
                value_nm=statistics.fmean(values),
                definition="afm_half_height",
                origin="measured",
                conditions=conditions,
                uncertainty_nm=statistics.stdev(values) if len(values) > 1 else None,
                n=len(values),
            )
            observations[quantity].append(
                deconvolve_tip(
                    raw,
                    feature_height_nm=median_height,
                    # The flag demands a measured value, so the operator is
                    # asserting one. Recorded as exactly that: stated, with
                    # no instrument, rather than read from a session record.
                    tip_radius_nm=Measured.stated(
                        tip_radius, "tip_radius", source="--tip-radius on the command line"
                    ),
                ).observation
            )
        population(particles, length_nm=quantities[0][1], width_nm=quantities[1][1], height_nm=2.0)

    results = {q: compare(q, obs) for q, obs in observations.items()}
    payload = {
        "part": part,
        "design_sha256": _design_hash(built.design),
        "sources": {
            "designed": True,
            "simulated": run_dir is not None and str(run_dir),
            "measured": scan is not None and str(scan),
        },
        "tip_radius_nm": tip_radius,
        "comparisons": {q: c.as_dict() for q, c in results.items()},
        "agrees": all(c.agrees for c in results.values()),
        "compared_anything": any(c.compared_anything for c in results.values()),
    }
    body = "\n\n".join(c.summary() for c in results.values())
    if not payload["compared_anything"]:
        body += "\n\nNothing was compared. Supply --run, --scan, or both."
    emitter.result(payload, f"closed loop: {part}\n" + body)


@app.command("export")
def export_command(
    part: str = PART_ARGUMENT,
    experiment: Path | None = typer.Option(
        None,
        "--experiment",
        help="An experiment folder of this part. Its protocols, and its comparison once "
        "post/ is complete, go in -- only if its provenance chain names this design.",
    ),
    out: Path = typer.Option(Path("exports"), "--out", help="Directory to write the zip into."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Write a local archive of a part in Nanobase's layout. Never uploads.

    Design files, oxDNA topology and configuration, an idealised image and a
    record of Nanobase's three upload forms, validated as it is written. A
    person may deposit it later through Nanobase's own form; this command
    talks to nothing but the disk. See `dobladillo.export` for the layout
    and the public documentation it was taken from.
    """
    from dobladillo.export import ExportRefused, export_part

    emitter = Emitter(as_json)
    built = _make_part(part, emitter)
    if experiment is not None and not (experiment / "pre").is_dir():
        emitter.fail(f"{experiment} is not an experiment folder", kind="missing_directory")
        return
    try:
        result = export_part(
            part=part, design=built.design, info=built.as_dict(), out=out, experiment=experiment
        )
    except ExportRefused as e:
        emitter.fail(str(e), kind=e.kind)
        return
    payload = result.as_dict()
    rows = [
        ("wrote", str(result.path)),
        ("sha256", result.sha256),
        ("design", payload["provenance"]["design_sha256"][:8]),
    ]
    rows += [(category, f"{n} file(s)") for category, n in payload["files"].items() if n]
    rows += [(f"not included: {k}", v) for k, v in payload["not_included"].items()]
    rows.append(("valid", "yes" if result.valid else f"NO, {len(result.problems)} problems"))
    rows.append(("uploaded", "no -- dobladillo never uploads"))
    body = f"{part}: export\n" + _table(rows)
    for problem in result.problems:
        body += f"\n  PROBLEM  {problem}"
    emitter.result(payload, body)
    if not result.valid:
        raise typer.Exit(1)


@app.command("export-check")
def export_check_command(
    archive: Path = typer.Argument(..., help="A zip written by `dobladillo export`."),
    as_json: bool = JSON_OPTION,
) -> None:
    """Validate an export archive against its layout. Exits non-zero if it departs."""
    from dobladillo.export import LAYOUT, validate
    from dobladillo.provenance import file_sha256

    emitter = Emitter(as_json)
    if not archive.is_file():
        emitter.fail(f"no such file: {archive}", kind="missing_file", code=2)
        return
    problems = validate(archive)
    payload = {
        "archive": str(archive),
        "sha256": file_sha256(archive),
        "layout": LAYOUT,
        "valid": not problems,
        "problems": problems,
    }
    body = f"{archive}\n" + _table([("layout", LAYOUT), ("valid", "yes" if not problems else "NO")])
    for problem in problems:
        body += f"\n  PROBLEM  {problem}"
    emitter.result(payload, body)
    if problems:
        raise typer.Exit(1)


@app.command("dashboard")
def dashboard_command(
    out: Path = typer.Option(Path("site"), "--out", help="Directory to write index.html into."),
    experiments_root: Path = typer.Option(
        Path("experiments"), "--experiments", help="Where experiment folders live."
    ),
    runs_root: Path = typer.Option(
        Path("runs"),
        "--runs",
        help="Where finished oxDNA runs live, one directory per part. Their "
        "trajectories become the simulated outline on the shape card.",
    ),
    as_json: bool = JSON_OPTION,
) -> None:
    """Generate the shareable board. Reads every figure from the toolchain.

    Regenerating is the only way to change the page, which is the point: the
    hand-written version it replaced had to carry a note in its own README
    admitting it would go stale.
    """
    import datetime as _dt

    from dobladillo.dashboard import gather, render

    emitter = Emitter(as_json)
    state = gather(experiments_root=experiments_root, runs_root=runs_root)
    stamp = _dt.datetime.now(_dt.UTC).strftime("Generated %Y-%m-%d %H:%M UTC.")
    out.mkdir(parents=True, exist_ok=True)
    page = out / "index.html"
    page.write_text(render(state, generated=stamp))

    payload = {"file": str(page), "bytes": page.stat().st_size, **state.as_dict()}
    ready = [e for e in state.experiments if e.ready]
    broken = [p for p in state.parts if not p.clean]
    rows = [
        ("wrote", str(page)),
        ("ready to run", ", ".join(e.id for e in ready) or "nothing"),
        ("critical path", f"{' -> '.join(state.critical_path)} = {state.critical_probability:.0%}"),
        ("programme cost", f"EUR {state.programme_cost['total_eur']:,.0f}"),
        (
            "parts failing lint",
            ", ".join(f"{p.name} ({p.worst})" for p in broken) or "none",
        ),
    ]
    emitter.result(payload, "dashboard\n" + _table(rows))


