"""Command line interface, readable by a person and parseable by an agent.

Every command takes `--json`. With it, stdout carries exactly one JSON object
and nothing else: no banners, no progress, no colour. Without it, the same data
is laid out for a human. The two are generated from one structure, so they
cannot drift apart and quietly disagree.

Three things make this usable by an agent rather than merely scriptable:

- `dobladillo describe --json` emits the whole command surface -- commands,
  parameters, types, defaults, output keys -- so capabilities can be discovered
  without scraping `--help`.
- Failures are JSON too, on stdout, with a stable `error` key and a non-zero
  exit code. An agent never has to tell a stack trace from a result.
- Warnings go to stderr, so a `--json` stdout stays machine-clean even when
  something is worth saying.
"""

from __future__ import annotations

import json
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import typer

from dobladillo import __version__
from dobladillo import _scadnano as ad
from dobladillo.parts import bundle as _bundle
from dobladillo.parts import hinge as _hinge
from dobladillo.parts import rectangle as _rectangle

app = typer.Typer(help="DNA origami brick toolchain.", no_args_is_help=True)
build_app = typer.Typer(help="Generate a part and write its files.", no_args_is_help=True)
app.add_typer(build_app, name="build")

JSON_OPTION = typer.Option(False, "--json", help="Emit one JSON object on stdout, nothing else.")
OUT_OPTION = typer.Option(None, "--out", help="Write .sc, cadnano v2 and oxview files here.")


@dataclass(frozen=True)
class Emitter:
    """Writes a result once, in whichever of the two shapes was asked for."""

    as_json: bool

    def result(self, payload: dict[str, Any], human: str) -> None:
        if self.as_json:
            typer.echo(json.dumps(payload, indent=2, sort_keys=False))
        else:
            typer.echo(human)

    def fail(self, message: str, *, kind: str = "error", code: int = 1) -> None:
        """Fail the same way in both modes: never a bare traceback."""
        if self.as_json:
            typer.echo(json.dumps({"error": {"kind": kind, "message": message}}, indent=2))
        else:
            typer.echo(f"error: {message}", err=True)
        raise typer.Exit(code)

    def note(self, message: str) -> None:
        """Say something without polluting a --json stdout."""
        typer.echo(message, err=True)


def _post_report(
    *,
    directory: Path,
    state: Any,
    measurements: dict[str, Any],
    results: dict[str, Any],
    chain: Any = None,
) -> str:
    """The page a person reads. Verdict first, caveats kept, nothing hidden."""
    agrees = all(r.agrees for r in results.values())
    lines = [
        f"# {directory.name}: result",
        "",
        "*Generated by `dobladillo experiment report`. Edit the interpretation below",
        "the line; everything above it is regenerated and will be overwritten.*",
        "",
        f"**{'Agrees with prediction' if agrees else 'DISAGREES with prediction'}**",
        "",
        f"- {measurements['particles']} particles clear of the frame edge",
        f"- tip radius {measurements['tip_radius_nm']:.1f} nm"
        + (
            f", blunted {100 * measurements['tip_blunting_fraction']:.0f}% during the session"
            if measurements["tip_blunting_fraction"]
            else ""
        ),
        f"- median height {measurements['median_height_nm']:.2f} nm",
        "",
    ]
    for result in results.values():
        lines += ["```", result.summary(), "```", ""]
    if state.problems:
        lines += ["## Problems with the record", ""]
        lines += [f"- {p}" for p in state.problems]
        lines += [""]
    if chain is not None:
        from dobladillo.provenance import short

        lines += [
            "## Provenance",
            "",
            f"- design `{short(chain.predicted_design)}`"
            + ("" if chain.predicted_design else " (no design hash recorded)"),
            f"- order made from design `{short(chain.scan_design)}`",
            f"- {len(chain.scans)} scan(s), hashes in `comparison.json`",
            f"- chain {'VERIFIED' if chain.verified else 'NOT verified'}",
            "",
        ]
    lines += [
        "## Against the gate",
        "",
        "The gate is in `pre/plan.md`. Nothing here evaluates it: whether this",
        "result passes is a judgement about the experiment, and the numbers above",
        "are only one input to it.",
        "",
        "---",
        "",
        "## Interpretation",
        "",
        "",
    ]
    return "\n".join(lines)


def _protocol_markdown(part: str, sheet: dict[str, Any]) -> str:
    """The protocol sheet as a page to follow at a bench, not as JSON.

    A protocol is read standing up next to a thermocycler, so it is markdown
    with the numbers already substituted. `dobladillo lab protocol --json`
    remains the machine-readable form.
    """
    anneal = sheet["anneal"]
    buffer_ = sheet["buffer"]
    lines = [
        f"# {part}: folding protocol",
        "",
        "Generated when this experiment was created. If you change anything,",
        "change it in `during/log.md` as a deviation rather than editing here --",
        "this file is what was *meant* to happen.",
        "",
        "## Buffer",
        "",
        f"{buffer_['tris_mm']} mM Tris, {buffer_['edta_mm']} mM EDTA, pH {buffer_['ph']}.",
        "",
        "## Magnesium screen",
        "",
        "Origami folding is sharply Mg-dependent, so this is a screen rather than",
        "a value. One reaction each at, in mM:",
        "",
        "  " + ", ".join(f"{m:g}" for m in sheet["magnesium_screen_mm"]),
        "",
        f"{len(sheet['reactions'])} reactions of "
        f"{sheet['reactions'][0]['volume_ul']:g} ul. Scaffold "
        f"{sheet['reactions'][0]['scaffold']['variant']} at "
        f"{sheet['reactions'][0]['scaffold']['final_nm']:g} nM, each staple at "
        f"{sheet['reactions'][0]['staples_final_nm_each']:g} nM.",
        "",
        "## Anneal",
        "",
        f"1. Hold at {anneal['hold']['temperature_c']} C for {anneal['hold']['minutes']:g} min.",
        f"2. Ramp {anneal['ramp']['from_c']} to {anneal['ramp']['to_c']} C at "
        f"{anneal['ramp']['rate']:g} {anneal['ramp']['rate_unit']}.",
        f"3. Total {anneal['total_hours']} h.",
        "",
        "## Purification",
        "",
        "  " + " / ".join(sheet["purification"]),
        "",
        "## Record for every reaction",
        "",
        "Into `during/log.md`. A reaction whose conditions were not recorded",
        "cannot be compared with one whose were.",
        "",
    ]
    lines += [f"- {item}" for item in sheet["record_for_each_reaction"]]
    lines += ["", sheet["note"], ""]
    return "\n".join(lines)


def _experiment_plan(*, slug: str, part: str, prediction: dict[str, Any]) -> str:
    predicted = prediction["predicted_nm"]
    return f"""# {slug}

**Part.** `{part}`

## What this is for

One paragraph. What question does this answer, and what would change if the
answer came back the other way? If nothing would change, the experiment is not
worth the oligos.

## The gate

**Write this before taking data.** What result makes this a failure?

A gate decided afterwards is a description of the data. This is the single
most important line in the folder, and it is the one most easily written last.

> criterion:

## What is predicted

From `pre/prediction.json`, recorded when this folder was made:

| quantity | predicted |
|---|---|
| length | {predicted["length"]} nm |
| width | {predicted["width"]} nm |
| height | {predicted["height"]} nm |

An AFM will not measure these directly. A half-height footprint is wider than
the object by twice `sqrt(R h - h^2/4)` for a tip of radius R -- about 8.7 nm
for a 10 nm tip on a 2 nm plate, which is a quarter of a 36 nm width. The
toolchain removes it in `post/`, using the tip radius from
`during/instrument.json`, which is why that field is not optional.

## Checklist before starting

- [ ] Gate written above
- [ ] `pre/` committed to git, so the prediction provably predates the data
- [ ] Oligos ordered from `pre/order/`
- [ ] Tip radius measured and written into `during/instrument.json`
"""


def _median(array: Any) -> float:
    import numpy as np

    return float(np.median(array))


def _table(rows: list[tuple[str, str]], *, indent: str = "  ") -> str:
    if not rows:
        return ""
    width = max(len(k) for k, _ in rows)
    return "\n".join(f"{indent}{k.ljust(width)}  {v}" for k, v in rows)


